"""Write kat/sir_kat.txt, kat/sir_kat.csv and kat/sir_kat.mem.

Each vector has a key, an IV, 64 keystream bytes, a 64-byte plaintext
and the matching ciphertext (plaintext XOR keystream).

sir_kat.mem is read by the testbenches with $readmemh. Per vector it
holds 216 bytes, one per line: key (16), iv (8), keystream (64),
plaintext (64), ciphertext (64).

Run from the repository root:  python3 model/gen_kat.py
"""

import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sir import SIR  # noqa: E402

NBYTES = 64
SEED = 2026
OUT_DIR = Path(__file__).resolve().parent.parent / "kat"


def vectors():
    fixed = [
        ("all_zero", "00" * 16, "00" * 8),
        ("all_one", "ff" * 16, "ff" * 8),
        ("incrementing", "000102030405060708090a0b0c0d0e0f", "0001020304050607"),
        ("pattern", "00112233445566778899aabbccddeeff", "0123456789abcdef"),
    ]
    for name, k, v in fixed:
        yield name, bytes.fromhex(k), bytes.fromhex(v)
    rnd = random.Random(SEED)
    for n in range(4):
        key = bytes(rnd.getrandbits(8) for _ in range(16))
        iv = bytes(rnd.getrandbits(8) for _ in range(8))
        yield f"random_{n + 1}", key, iv


def plaintext(index: int) -> bytes:
    return bytes((0x11 * j + 7 * index) & 0xFF for j in range(NBYTES))


def main() -> int:
    OUT_DIR.mkdir(exist_ok=True)
    txt, csv, mem = [], ["index,name,key,iv,keystream,plaintext,ciphertext"], []

    txt.append("# SIR known-answer test vectors")
    txt.append("# Generated by model/gen_kat.py from model/sir.py.")
    txt.append(f"# Keystream: first {NBYTES} bytes after the 32-round warm-up,")
    txt.append("# first keystream bit in the MSB of the first byte.")
    txt.append("# Ciphertext = plaintext XOR keystream.")

    for idx, (name, key, iv) in enumerate(vectors(), start=1):
        ks = SIR(key, iv).keystream(NBYTES)
        pt = plaintext(idx)
        ct = bytes(a ^ b for a, b in zip(pt, ks))

        txt.append("")
        txt.append(f"Vector     : {idx} ({name})")
        txt.append(f"Key        : {key.hex()}")
        txt.append(f"IV         : {iv.hex()}")
        for label, data in (("Keystream", ks), ("Plaintext", pt), ("Ciphertext", ct)):
            for row in range(0, NBYTES, 32):
                head = f"{label:<11}: " if row == 0 else " " * 13
                txt.append(head + data[row:row + 32].hex())

        csv.append(",".join([str(idx), name, key.hex(), iv.hex(), ks.hex(), pt.hex(), ct.hex()]))

        mem.append(f"// vector {idx} ({name}): key, iv, keystream, plaintext, ciphertext")
        for data in (key, iv, ks, pt, ct):
            mem.extend(f"{b:02x}" for b in data)

    (OUT_DIR / "sir_kat.txt").write_text("\n".join(txt) + "\n")
    (OUT_DIR / "sir_kat.csv").write_text("\n".join(csv) + "\n")
    (OUT_DIR / "sir_kat.mem").write_text("\n".join(mem) + "\n")
    print(f"wrote {idx} vectors to {OUT_DIR.name}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
